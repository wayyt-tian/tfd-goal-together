-- PostgreSQL 16；事务内计数器的行锁保证事件提交顺序。
CREATE TABLE event_clock (id INTEGER PRIMARY KEY CHECK(id=1), value BIGINT NOT NULL DEFAULT 0);
INSERT INTO event_clock(id) VALUES(1);
CREATE FUNCTION next_event_seq() RETURNS BIGINT LANGUAGE sql VOLATILE AS $$
  UPDATE event_clock SET value=value+1 WHERE id=1 RETURNING value;
$$;

CREATE TABLE metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);

CREATE TABLE departments (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, parent_id INTEGER, manager_id INTEGER, deleted INTEGER NOT NULL DEFAULT 0);

CREATE TABLE users (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, phone TEXT, credential TEXT, department_id INTEGER, role TEXT NOT NULL DEFAULT 'member', active INTEGER NOT NULL DEFAULT 1, manager_id INTEGER, title TEXT NOT NULL DEFAULT '');

CREATE TABLE sessions (token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL, csrf TEXT NOT NULL, expires BIGINT NOT NULL);

CREATE TABLE audit (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor INTEGER, action TEXT NOT NULL, subject TEXT, created_at TIMESTAMPTZ NOT NULL);

CREATE TABLE directory_profiles (user_id INTEGER PRIMARY KEY, source_id TEXT NOT NULL, source_company TEXT NOT NULL, alternate_names JSONB NOT NULL DEFAULT '[]', direct_manager_id INTEGER, source_row INTEGER, UNIQUE(source_company,source_id));

CREATE TABLE goals ( id TEXT PRIMARY KEY, parent_id TEXT, scope TEXT NOT NULL, kind TEXT NOT NULL, title TEXT NOT NULL, note TEXT NOT NULL DEFAULT '', unit TEXT NOT NULL DEFAULT '', target NUMERIC(24,4), start_date DATE NOT NULL, end_date DATE NOT NULL, owner_id INTEGER NOT NULL, org_ids JSONB NOT NULL DEFAULT '[]', align_id TEXT, created_by INTEGER NOT NULL, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, version INTEGER NOT NULL DEFAULT 1, archived_at TIMESTAMPTZ, archived_by INTEGER, archive_root TEXT, done_at TIMESTAMPTZ, done_by INTEGER, sort REAL NOT NULL DEFAULT 0, seq BIGINT NOT NULL DEFAULT 0, legacy_ref TEXT);

CREATE TABLE goal_members (goal_id TEXT NOT NULL, user_id INTEGER NOT NULL, added_by INTEGER, added_at TIMESTAMPTZ NOT NULL, PRIMARY KEY (goal_id, user_id));

CREATE TABLE checkins ( ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE, id TEXT PRIMARY KEY, goal_id TEXT NOT NULL, author_id INTEGER NOT NULL, date DATE NOT NULL, value NUMERIC(24,4), note TEXT NOT NULL DEFAULT '', signal TEXT, created_at TIMESTAMPTZ NOT NULL, voided_at TIMESTAMPTZ, voided_by INTEGER, void_reason TEXT, legacy_ref TEXT, simulated INTEGER NOT NULL DEFAULT 0);

CREATE TABLE events ( seq BIGINT PRIMARY KEY DEFAULT next_event_seq(), created_at TIMESTAMPTZ NOT NULL, actor_id INTEGER, type TEXT NOT NULL, goal_id TEXT, ref_id TEXT, payload JSONB NOT NULL DEFAULT '{}');

CREATE TABLE cheers (event_seq BIGINT NOT NULL, user_id INTEGER NOT NULL, created_at TIMESTAMPTZ NOT NULL, PRIMARY KEY (event_seq, user_id));

CREATE TABLE user_state (user_id INTEGER PRIMARY KEY, last_seen_seq BIGINT NOT NULL DEFAULT 0, onboarded INTEGER NOT NULL DEFAULT 0);

CREATE UNIQUE INDEX active_phone ON users(phone) WHERE active = 1 AND phone IS NOT NULL;  -- 在职成员手机号唯一
CREATE INDEX goals_parent ON goals(parent_id);
CREATE INDEX goals_owner ON goals(owner_id);
CREATE INDEX goals_seq ON goals(seq);
CREATE INDEX goal_members_user ON goal_members(user_id);
CREATE INDEX checkins_goal ON checkins(goal_id, date);
CREATE INDEX checkins_author ON checkins(author_id, created_at);
CREATE INDEX events_goal ON events(goal_id, seq);

CREATE INDEX checkins_effective ON checkins(goal_id,date) INCLUDE(value,signal,created_at) WHERE voided_at IS NULL;
CREATE INDEX checkins_signal ON checkins(goal_id,created_at DESC,ordinal DESC) WHERE voided_at IS NULL AND signal IS NOT NULL;
CREATE INDEX sessions_expiry ON sessions(expires);
CREATE INDEX sessions_user ON sessions(user_id);
CREATE INDEX users_manager ON users(manager_id) WHERE active=1;
CREATE INDEX users_department ON users(department_id) WHERE active=1;
CREATE INDEX events_type_seq ON events(type,seq DESC);
CREATE INDEX events_actor_seq ON events(actor_id,seq DESC);
CREATE INDEX cheers_recipient ON cheers(user_id,event_seq);
CREATE INDEX goals_archive ON goals(archive_root) WHERE archived_at IS NOT NULL;
CREATE INDEX profiles_manager ON directory_profiles(direct_manager_id);
